// Real Offline Language Pack Files System (ملفات حزم اللغات بدون نت)
// Each pack represents a downloadable offline language package containing words, phrases, and sentence patterns.

export interface PackVocabularyItem {
  term: string; // The original headword or phrase
  normalized: string; // Normalized for instant fuzzy search
  pos: 'noun' | 'verb' | 'adjective' | 'phrase' | 'sentence' | 'number' | 'question' | 'greeting';
  translations: Record<string, string>; // Translations in ar, en, fr, es, de, tr, it, ru, zh, ja
  alternatives?: string[];
  explanationAr?: string;
  explanationEn?: string;
}

export interface SentenceTemplate {
  patternAr: RegExp;
  templateTarget: Record<string, (match: RegExpMatchArray, translateEntity: (term: string) => string) => string>;
}

