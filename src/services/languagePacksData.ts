// Helper to look up any word or phrase from the pack database
export function lookupPackItem(query: string, fromLang: string, toLang: string): string | null {
  const clean = query.trim().toLowerCase().replace(/[.,?!؛:،]/g, '');
  if (!clean) return null;

  for (const item of PACK_DATABASE) {
    // Check if query matches in source language
    const srcVal = item.translations[fromLang] || item.translations.ar || item.translations.en;
    if (srcVal) {
      const srcClean = srcVal.toLowerCase().replace(/[.,?!؛:،]/g, '').trim();
      if (srcClean === clean || item.normalized === clean) {
        return item.translations[toLang] || null;
      }
    }

    // Check all translation values for bidirectional matching
    for (const [lang, val] of Object.entries(item.translations)) {
      const vClean = val.toLowerCase().replace(/[.,?!؛:،]/g, '').trim();
      if (vClean === clean) {
        return item.translations[toLang] || null;
      }
    }
  }

  return null;
}
